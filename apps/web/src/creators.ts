/** Which creator slugs share a mark, e.g. both Meta namespaces. */
const ICON_ALIASES: Record<string, string> = {
  "bytedance-seed": "bytedance",
  "meta-llama": "meta",
  qwen: "alibabacloud",
  "x-ai": "x",
};

export function brandIcon(slug: string): BrandIcon | undefined {
  const icon = BRAND_ICONS[slug] ?? BRAND_ICONS[ICON_ALIASES[slug]];
  if (!icon) return undefined;
  return { d: icon.d, hex: legibleHex(icon.hex) };
}

/** Relative luminance, 0 (black) to 1 (white). */
function luminance(hex: string): number {
  const channels = [0, 2, 4].map((offset) => parseInt(hex.slice(offset, offset + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/**
 * A few brands ship a near-black mark (Anthropic, X), which disappears against
 * the app's dark surface. Lighten those towards white and leave the rest at
 * their real brand colour.
 */
function legibleHex(hex: string): string {
  if (luminance(hex) > 0.06) return hex;
  const mix = 0.72;
  const channels = [0, 2, 4].map((offset) => {
    const value = parseInt(hex.slice(offset, offset + 2), 16);
    return Math.round(value + (255 - value) * mix)
      .toString(16)
      .padStart(2, "0");
  });
  return channels.join("").toUpperCase();
}

/** The letter shown when a creator has no brand mark. */
export function creatorInitial(name: string): string {
  return name.trim().charAt(0).toUpperCase() || "?";
}
