/**
 * A model "creator" is the lab that trained the model, which is not the same
 * thing as the provider serving it: almost every model here arrives through
 * OpenRouter, but the interesting grouping is Anthropic / OpenAI / Qwen / ...
 *
 * The id is `${providerId}/${modelId}`, and aggregators like OpenRouter prefix
 * the model id with the creator's namespace, so `openrouter/anthropic/claude-…`
 * yields `anthropic`. Direct providers have no namespace and are their own
 * creator.
 */

/** Provider ids that namespace their models by creator. */
const NAMESPACED_PROVIDERS = new Set(["openrouter"]);

export function creatorSlug(model: ModelInfo): string {
  const parts = model.id.split("/");
  if (NAMESPACED_PROVIDERS.has(parts[0]) && parts.length >= 3) {
    // OpenRouter prefixes free-tier variants with `~`.
    return parts[1].replace(/^~/, "");
  }
  return parts[0];
}

