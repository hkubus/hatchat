/** "ibm-granite" -> "Ibm Granite" as a last resort. */
function prettify(slug: string): string {
  return slug
    .split(/[-.]/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

/** The label prefix ("Anthropic: Claude Sonnet 5.5" -> "Anthropic"), if present. */
function labelPrefix(model: ModelInfo): string | undefined {
  const match = /^([^:]{2,40}):\s/.exec(model.label);
  return match?.[1].trim();
}

/**
 * The bare model name, with the creator prefix OpenRouter puts in the label
 * stripped. The picker already groups by creator, so repeating it on every row
 * is noise.
 */
export function modelName(model: ModelInfo): string {
  return model.label.replace(/^[^:]{2,40}:\s*/, "").trim() || model.id;
}

/** The name for a creator, judged from one model. */
export function creatorName(model: ModelInfo): string {
  const slug = creatorSlug(model);
  return CREATOR_NAMES[slug] ?? labelPrefix(model) ?? prettify(slug);
}

/**
 * The model id without its provider and creator namespace:
 * `openrouter/aion-labs/aion-3.5-mini` -> `aion-3.5-mini`.
 */
export function shortModelId(model: ModelInfo): string {
  return model.id.split("/").pop() ?? model.id;
}

export interface Creator {
  slug: string;
  name: string;
  models: ModelInfo[];
}

/**
 * Group models by creator. Names are resolved from the curated map, then the
 * most common label prefix, then the prettified slug — providers are
 * inconsistent about label prefixes within a single creator. Slugs that resolve
 * to the same name (OpenRouter's `meta` and `meta-llama`, say) are merged.
 */
export function groupByCreator(models: ModelInfo[]): Creator[] {
  const bySlug = new Map<string, ModelInfo[]>();
  for (const model of models) {
    const slug = creatorSlug(model);
    const list = bySlug.get(slug) ?? [];
    list.push(model);
    bySlug.set(slug, list);
  }

  const byName = new Map<string, Creator>();
  for (const [slug, list] of bySlug) {
    let name = CREATOR_NAMES[slug];
    if (!name) {
      const counts = new Map<string, number>();
      for (const model of list) {
        const prefix = labelPrefix(model);
        if (prefix) counts.set(prefix, (counts.get(prefix) ?? 0) + 1);
      }
      const [topPrefix, topCount] = [...counts.entries()].sort((a, b) => b[1] - a[1])[0] ?? [];
      // Only trust the prefix if most of the creator's models agree on it.
      name = topCount !== undefined && topCount * 2 >= list.length ? topPrefix : prettify(slug);
    }

    const existing = byName.get(name);
    if (existing) {
      existing.models.push(...list);
      continue;
    }
    byName.set(name, { slug, name, models: list });
  }

  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

